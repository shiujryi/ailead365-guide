const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()}: ${response.url()}`); });
  const url = process.env.SITE_URL || 'http://127.0.0.1:8000/';
  await page.goto(url);
  assert.equal(await page.title(), 'AILEAD365 使用指南｜基隆市立中山高級中學');
  for (const [width, height] of [[1440,1000],[1024,900],[820,1180],[768,1024],[760,900],[390,844],[320,740]]) {
    await page.setViewportSize({width,height});
    for (const role of ['senior','junior','teacher']) {
      await page.locator(`#tab-${role}`).click();
      await page.waitForTimeout(100);
      assert.equal(await page.locator('[role="tabpanel"]:visible').count(), 1);
      assert.equal(await page.locator(`#tab-${role}`).getAttribute('aria-selected'), 'true');
      await page.locator(`#panel-${role}`).waitFor({state:'visible'});
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
      assert.equal(overflow, false, `Horizontal overflow: ${width}px / ${role}`);
    }
    console.log(`PASS responsive layout and 3 roles: ${width}px`);
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#tab-senior').focus();
  await page.keyboard.press('ArrowRight');
  await page.locator('#panel-junior').waitFor({state:'visible'});
  assert.equal(await page.locator('#tab-junior').evaluate(el => el === document.activeElement),true);
  await page.keyboard.press('End');
  await page.locator('#panel-teacher').waitFor({state:'visible'});
  await page.keyboard.press('Home');
  await page.locator('#panel-senior').waitFor({state:'visible'});
  await page.keyboard.press('ArrowLeft');
  await page.locator('#panel-teacher').waitFor({state:'visible'});
  await page.keyboard.press('ArrowRight');
  await page.locator('#panel-senior').waitFor({state:'visible'});
  console.log('PASS tab keyboard navigation and wrapping');
  await page.locator('[data-filter="login"]').click();
  assert.equal(await page.locator('.faq-item:visible').count(),4);
  await page.locator('.faq-item:visible summary').first().click();
  assert.equal(await page.locator('.faq-item:visible').first().getAttribute('open'),'');
  await page.locator('[data-filter="learning"]').click();
  assert.equal(await page.locator('.faq-item:visible').count(),4);
  await page.locator('[data-filter="all"]').click();
  assert.equal(await page.locator('.faq-item:visible').count(),8);
  console.log('PASS FAQ filtering, counts and disclosure');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.menu-toggle').click();
  assert.equal(await page.locator('.site-nav').isVisible(),true);
  await page.locator('.site-nav a[href="#faq"]').click();
  assert.equal(await page.locator('.site-nav').isVisible(),false);
  await page.locator('.menu-toggle').click();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'false');
  assert.equal(await page.locator('.menu-toggle').evaluate(el => el === document.activeElement),true);
  console.log('PASS mobile menu, anchor close, Escape and focus');
  assert.equal(await page.locator('form,input').count(),0);
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length),0);
  const loginLinks = await page.locator('a[href*="ailead365.com"]').evaluateAll(links => links.map(a=>a.href));
  assert(loginLinks.length >= 3 && loginLinks.every(href=>href==='https://csjhkl.ailead365.com/auth/login'));
  console.log('PASS privacy, no browser storage and login link destinations');
  await page.locator('#tab-senior').click();
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>scrollTo(0,0));
  if (process.env.SCREENSHOT_DIR) await page.screenshot({path:require('node:path').join(process.env.SCREENSHOT_DIR,'ailead365-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if (process.env.SCREENSHOT_DIR) await page.screenshot({path:require('node:path').join(process.env.SCREENSHOT_DIR,'ailead365-mobile.png'),fullPage:true});
  const nojs = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const fallback = await nojs.newPage();
  await fallback.goto(url);
  assert.equal(await fallback.locator('[role="tabpanel"]:visible').count(),3);
  assert.equal(await fallback.locator('.site-nav').isVisible(),true);
  assert.equal(await fallback.locator('.faq-item:visible').count(),8);
  await fallback.locator('summary').first().click();
  assert.equal(await fallback.locator('details').first().getAttribute('open'),'');
  console.log('PASS no-JavaScript guides, navigation and native FAQ');
  assert.deepEqual(errors,[]);
  console.log('PASS no failed assets or JavaScript runtime errors');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
